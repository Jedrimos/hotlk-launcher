const { contextBridge, ipcRenderer } = require('electron');
const inv = (c, ...a) => ipcRenderer.invoke(c, ...a);
contextBridge.exposeInMainWorld('api', {
  getConfig: () => inv('config:get'),
  setConfig: (p) => inv('config:set', p),
  detectGames: () => inv('game:detect'),
  setGame: (d) => inv('game:set', d),
  login: (u, p, r) => inv('auth:login', u, p, r),
  restore: () => inv('auth:restore'),
  logout: () => inv('auth:logout'),
  isRunning: () => inv('game:running'),
  defaultTarget: () => inv('game:defaultTarget'),
  serverStatus: () => inv('server:status'),
  launcherVersion: () => inv('launcher:version'),
  pickGame: () => inv('game:pick'),
  news: () => inv('news:get'),
  packStatus: () => inv('packs:status'),
  download: (id) => inv('packs:download', id),
  syncBase: (deep) => inv('base:sync', deep),
  cancel: () => inv('packs:cancel'),
  removePack: (id) => inv('packs:remove', id),
  realmStatus: () => inv('realms:status'),
  addonsInstalled: () => inv('addons:installed'),
  addonToggle: (n, on) => inv('addons:toggle', n, on),
  addonRemove: (n) => inv('addons:remove', n),
  addonCatalog: () => inv('addons:catalog'),
  addonInstall: (id) => inv('addons:install', id),
  onAddonProgress: (cb) => ipcRenderer.on('addons:progress', (_e, p) => cb(p)),
  accounts: () => inv('auth:accounts'), switchAccount: (u) => inv('auth:switch', u), forgetAccount: (u) => inv('auth:forget', u),
  preflight: () => inv('game:preflight'),
  backups: () => inv('tools:backups'), backupCreate: () => inv('tools:backupCreate'), backupRestore: (n) => inv('tools:backupRestore', n), backupDelete: (n) => inv('tools:backupDelete', n), wtfReset: () => inv('tools:wtfReset'),
  gfxGet: () => inv('tools:gfxGet'), gfxSet: (p) => inv('tools:gfxSet', p),
  diagnose: () => inv('tools:diagnose'), fix: (id) => inv('tools:fix', id),
  crashLatest: () => inv('tools:crashLatest'), crashSend: () => inv('tools:crashSend'),
  serverInfo: (fresh) => inv('server:info', fresh), onData: (cb) => ipcRenderer.on('data:updated', (_e, n, d) => cb(n, d)), players: () => inv('server:players'), admin: (a, d) => inv('admin:run', a, d),
  updateLauncher: () => inv('launcher:update'), onUpdateProgress: (cb) => ipcRenderer.on('update:progress', (_e, p) => cb(p)),
  addonUpdates: () => inv('addons:updates'),
  onPhase: (cb) => ipcRenderer.on('game:phase', (_e, t) => cb(t)),
  play: () => inv('game:play'),
  sysinfo: () => inv('support:sysinfo'), copyText: (t) => inv('support:copy', t), openLog: () => inv('support:openLog'), logError: (l, m) => inv('support:log', l, m), sendReport: (o) => inv('support:report', o), setAutostart: (on) => inv('win:autostart', on),
  onCrashed: (cb) => ipcRenderer.on('game:crashed', (_e, p) => cb(p)),
  minimize: () => inv('win:min'),
  close: () => inv('win:close'),
  openUrl: (u) => inv('open:url', u),
  onProgress: (cb) => ipcRenderer.on('packs:progress', (_e, p) => cb(p))
});
